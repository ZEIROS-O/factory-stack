"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const crypto = require("node:crypto");
const { spawnSync } = require("node:child_process");

const ROOT = path.resolve(__dirname, "../..");
const ROLES = ["hermes", "engineer", "reviewer"];

function sha256(bytes) { return crypto.createHash("sha256").update(bytes).digest("hex"); }

function fixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "factory-instructions-"));
  const dir = path.join(root, "instructions");
  fs.mkdirSync(path.join(dir, "src"), { recursive: true });
  fs.mkdirSync(path.join(dir, "out"), { recursive: true });
  for (const name of ["_platform_contract.md", "_doctrine.md", ...ROLES.map((r) => `_role_${r}.md`)]) {
    fs.copyFileSync(path.join(ROOT, "instructions/src", name), path.join(dir, "src", name));
  }
  const lines = [];
  for (const role of ROLES) {
    const bytes = Buffer.concat([
      fs.readFileSync(path.join(dir, "src/_platform_contract.md")),
      fs.readFileSync(path.join(dir, "src/_doctrine.md")),
      fs.readFileSync(path.join(dir, `src/_role_${role}.md`)),
    ]);
    fs.writeFileSync(path.join(dir, `out/AGENTS.${role}.md`), bytes);
    lines.push(`${sha256(bytes)}  out/AGENTS.${role}.md`);
  }
  fs.writeFileSync(path.join(dir, "manifest.sha256"), lines.join("\n") + "\n");
  fs.copyFileSync(path.join(ROOT, "instructions/compile.sh"), path.join(dir, "compile.sh"));
  fs.chmodSync(path.join(dir, "compile.sh"), 0o755);

  const bin = path.join(root, "node_modules/.bin");
  fs.mkdirSync(bin, { recursive: true });
  fs.writeFileSync(path.join(bin, "paperclipai"), "#!/usr/bin/env bash\necho called >> \"$0.calls\"\nprintf '[]\\n'\n");
  fs.chmodSync(path.join(bin, "paperclipai"), 0o755);
  return { root, dir, calls: path.join(bin, "paperclipai.calls") };
}

test("compile --check is byte-read-only and makes zero Paperclip API calls", () => {
  const f = fixture();
  const before = fs.statSync(path.join(f.dir, "out/AGENTS.engineer.md")).mtimeNs;
  const result = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  const after = fs.statSync(path.join(f.dir, "out/AGENTS.engineer.md")).mtimeNs;
  assert.equal(result.status, 0, result.stderr || result.stdout);
  assert.equal(fs.existsSync(f.calls), false, "--check must never invoke Paperclip");
  assert.equal(after, before, "--check must not rewrite generated output");
});

test("compile --check fails closed on generated bundle or manifest drift without publishing", () => {
  const f = fixture();
  fs.appendFileSync(path.join(f.dir, "out/AGENTS.reviewer.md"), "drift\n");
  const result = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr + result.stdout, /drift|out of date|mismatch/i);
  assert.equal(fs.existsSync(f.calls), false, "a failed check must not publish either");
});

test("committed manifest is deterministic, complete, and matches generated bytes", () => {
  const lines = fs.readFileSync(path.join(ROOT, "instructions/manifest.sha256"), "utf8").trim().split("\n");
  assert.equal(lines.length, 3);
  assert.deepEqual(lines.map((line) => line.split(/\s+/)[1]), ROLES.map((r) => `out/AGENTS.${r}.md`));
  for (const line of lines) {
    const [want, rel] = line.split(/\s+/);
    assert.equal(sha256(fs.readFileSync(path.join(ROOT, "instructions", rel))), want);
  }
});
