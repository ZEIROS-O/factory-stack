"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const crypto = require("node:crypto");
const { spawnSync } = require("node:child_process");

const ROOT = path.resolve(__dirname, "../..");
const INSTR = path.join(ROOT, "instructions");

function sha256(bytes) { return crypto.createHash("sha256").update(bytes).digest("hex"); }

function readBundles() {
  return JSON.parse(fs.readFileSync(path.join(INSTR, "bundles.json"), "utf8"));
}

// Exact ordered concatenation of a role's declared fragments, from bundles.json.
function compose(bundles, role) {
  return Buffer.concat(bundles.bundles[role].map((f) =>
    fs.readFileSync(path.join(INSTR, "src", f))));
}

function committed(role) {
  return fs.readFileSync(path.join(INSTR, "out", `AGENTS.${role}.md`));
}

// A self-contained instructions/ tree whose out/ and manifest are composed
// generically from bundles.json, plus a call-recording paperclipai stub.
function fixture() {
  const bundles = readBundles();
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "factory-instructions-"));
  const dir = path.join(root, "instructions");
  fs.mkdirSync(path.join(dir, "src"), { recursive: true });
  fs.mkdirSync(path.join(dir, "out"), { recursive: true });
  const fragments = new Set(Object.values(bundles.bundles).flat());
  for (const name of fragments) {
    fs.copyFileSync(path.join(INSTR, "src", name), path.join(dir, "src", name));
  }
  const lines = [];
  for (const role of Object.keys(bundles.bundles)) {
    const bytes = compose(bundles, role);
    const out = path.join(dir, `out/AGENTS.${role}.md`);
    fs.writeFileSync(out, bytes, { mode: 0o444 });
    lines.push(`${sha256(bytes)}  out/AGENTS.${role}.md`);
  }
  fs.writeFileSync(path.join(dir, "manifest.sha256"), lines.join("\n") + "\n");
  fs.copyFileSync(path.join(INSTR, "compile.sh"), path.join(dir, "compile.sh"));
  fs.chmodSync(path.join(dir, "compile.sh"), 0o755);
  fs.copyFileSync(path.join(INSTR, "bundles.json"), path.join(dir, "bundles.json"));

  const bin = path.join(root, "node_modules/.bin");
  fs.mkdirSync(bin, { recursive: true });
  fs.writeFileSync(path.join(bin, "paperclipai"),
    "#!/usr/bin/env bash\necho called >> \"$0.calls\"\nprintf '[]\\n'\n");
  fs.chmodSync(path.join(bin, "paperclipai"), 0o755);
  return { root, dir, bundles, calls: path.join(bin, "paperclipai.calls") };
}

// Personal-context markers forbidden in every worker bundle.
const PERSONAL = /SOUL\.md|~\/\.claude|\bLou\b|\bZEIROS\b/i;

test("compile --check is byte-read-only and makes zero Paperclip API calls", () => {
  const f = fixture();
  const out = path.join(f.dir, "out/AGENTS.engineer.md");
  const before = fs.statSync(out).mtimeNs;
  const beforeBytes = fs.readFileSync(out);
  const result = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  assert.equal(fs.existsSync(f.calls), false, "--check must never invoke Paperclip");
  assert.equal(fs.statSync(out).mtimeNs, before, "--check must not rewrite generated output");
  assert.deepEqual(fs.readFileSync(out), beforeBytes, "--check must not change generated bytes");
});

test("compile --check fails closed on bundle drift without publishing", () => {
  const f = fixture();
  const out = path.join(f.dir, "out/AGENTS.reviewer.md");
  fs.chmodSync(out, 0o644); // 0444 cannot be appended in place
  fs.appendFileSync(out, "drift\n");
  fs.chmodSync(out, 0o444);
  const result = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr + result.stdout, /drift|out of date|mismatch/i);
  assert.equal(fs.existsSync(f.calls), false, "a failed check must not publish either");
});

test("compile --check fails closed on manifest drift without publishing", () => {
  const f = fixture();
  fs.appendFileSync(path.join(f.dir, "manifest.sha256"), "drift\n");
  const result = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr + result.stdout, /manifest|mismatch/i);
  assert.equal(fs.existsSync(f.calls), false, "a failed check must not publish either");
});

test("committed manifest is deterministic, complete, in bundles.json role order, and matches bytes", () => {
  const bundles = readBundles();
  const roles = Object.keys(bundles.bundles);
  const lines = fs.readFileSync(path.join(INSTR, "manifest.sha256"), "utf8").trim().split("\n");
  assert.equal(lines.length, roles.length);
  assert.deepEqual(lines.map((line) => line.split(/\s+/)[1]), roles.map((r) => `out/AGENTS.${r}.md`));
  for (const line of lines) {
    const [want, rel] = line.split(/\s+/);
    assert.match(want, /^[0-9a-f]{64}$/);
    assert.equal(sha256(fs.readFileSync(path.join(INSTR, rel))), want);
  }
});

test("each compiled bundle equals the exact ordered concatenation of its declared fragments", () => {
  const bundles = readBundles();
  for (const role of Object.keys(bundles.bundles)) {
    assert.deepEqual(committed(role), compose(bundles, role), `${role} bundle must equal its declared fragments in order`);
  }
});

test("fragment order is load-bearing: swapping two fragments changes the bundle", () => {
  const bundles = readBundles();
  for (const role of Object.keys(bundles.bundles)) {
    const frags = bundles.bundles[role];
    if (frags.length < 2) continue;
    const swapped = [frags[1], frags[0], ...frags.slice(2)];
    const reordered = Buffer.concat(swapped.map((f) => fs.readFileSync(path.join(INSTR, "src", f))));
    assert.notDeepEqual(reordered, committed(role), `${role} bundle must be order-sensitive`);
  }
});

test("every src/*.md fragment is referenced by at least one bundle", () => {
  const bundles = readBundles();
  const referenced = new Set(Object.values(bundles.bundles).flat());
  for (const name of fs.readdirSync(path.join(INSTR, "src"))) {
    assert.ok(referenced.has(name), `src/${name} is an orphan, referenced by no bundle`);
  }
  // The split removed the old shared doctrine and never introduces a platform contract.
  assert.equal(fs.existsSync(path.join(INSTR, "src", "_doctrine.md")), false);
  assert.equal(fs.existsSync(path.join(INSTR, "src", "_platform_contract.md")), false);
});

test("size caps hold: _core.md and each bundle stay within maxBytes from bundles.json", () => {
  const bundles = readBundles();
  const core = fs.readFileSync(path.join(INSTR, "src", "_core.md"));
  assert.ok(core.length <= bundles.maxBytes["_core.md"], "_core.md over its fragment cap");
  for (const role of Object.keys(bundles.bundles)) {
    assert.ok(committed(role).length <= bundles.maxBytes[role], `${role} bundle over its cap`);
  }
});

test("no compiled bundle has a duplicate `## ` heading", () => {
  const bundles = readBundles();
  for (const role of Object.keys(bundles.bundles)) {
    const headings = committed(role).toString("utf8").match(/^## .*$/gm) || [];
    const seen = new Set();
    for (const h of headings) {
      assert.ok(!seen.has(h), `${role} bundle duplicates heading "${h}"`);
      seen.add(h);
    }
  }
});

test("forbidden content is absent from the committed bundles", () => {
  const hermes = committed("hermes").toString("utf8");
  const engineer = committed("engineer").toString("utf8");
  const reviewer = committed("reviewer").toString("utf8");

  // Hermes carries no OMP goal/receipt material and no personal context.
  assert.doesNotMatch(hermes, /EXECUTION_RECEIPT_CLAIMS/i);
  assert.doesNotMatch(hermes, /goal\.complete/i);
  assert.doesNotMatch(hermes, /subagent/i);
  assert.doesNotMatch(hermes, /\btask\b/i);
  assert.doesNotMatch(hermes, PERSONAL);

  // Engineer carries no Hermes-intake or personal context.
  assert.doesNotMatch(engineer, /Hermes/i);
  assert.doesNotMatch(engineer, /intake/i);
  assert.doesNotMatch(engineer, /EngineerHandoffDraft/i);
  assert.doesNotMatch(engineer, PERSONAL);

  // Reviewer carries no delegation/task/goal/repair material.
  assert.doesNotMatch(reviewer, /subagent/i);
  assert.doesNotMatch(reviewer, /delegate/i);
  assert.doesNotMatch(reviewer, /EXECUTION_RECEIPT_CLAIMS_V1---/i);
  assert.doesNotMatch(reviewer, /goal\.complete/i);
  assert.doesNotMatch(reviewer, /repair/i);
});

// Mode is a property of what `--write` PRODUCES, not of what the repository
// stores: Git records only the executable bit, so every clone and checkout
// materializes these bundles 0644. Asserting 0444 on the committed files would
// pass only in the tree that happened to run the compiler last. Compile into a
// fixture and assert on that instead, which is the claim that actually holds.
test("compile --write installs generated output read-only", () => {
  const f = fixture();
  const result = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--write"], { encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  for (const role of Object.keys(readBundles().bundles)) {
    const mode = fs.statSync(path.join(f.dir, "out", `AGENTS.${role}.md`)).mode & 0o777;
    assert.equal(mode, 0o444, `${role} bundle must be written read-only`);
  }
});

test("compile --check tolerates a checked-out 0644 bundle but still catches an edit", () => {
  const f = fixture();
  for (const role of Object.keys(readBundles().bundles)) {
    fs.chmodSync(path.join(f.dir, "out", `AGENTS.${role}.md`), 0o644);
  }
  const clean = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  assert.equal(clean.status, 0, `0644 is a checkout artifact, not drift: ${clean.stderr}`);

  // The byte comparison, not the mode, is what defends against a hand edit.
  fs.appendFileSync(path.join(f.dir, "out", "AGENTS.hermes.md"), "hand edit\n");
  const edited = spawnSync("bash", [path.join(f.dir, "compile.sh"), "--check"], { encoding: "utf8" });
  assert.notEqual(edited.status, 0, "a writable hand-edited bundle must still fail --check");
  assert.match(edited.stderr + edited.stdout, /drift|out of date|mismatch/i);
});

test("the adapter-owned platform contract string is absent from every bundle", () => {
  const platformOpening = "You are an agent at Paperclip company.";
  const bundles = readBundles();
  for (const role of Object.keys(bundles.bundles)) {
    assert.equal(committed(role).toString("utf8").includes(platformOpening), false,
      "Paperclip's adapter owns the platform contract");
  }
});
